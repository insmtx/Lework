package opencode

import (
	"bufio"
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"strings"
	"time"
)

const (
	// defaultRequestTimeout bounds non-streaming calls so a wedged opencode
	// process cannot stall the agent forever. Callers that need otherwise
	// should pass an *http.Client carrying their own timeout.
	defaultRequestTimeout = 30 * time.Second

	// maxErrorBody caps how much of a failed response is echoed into an error.
	// Bodies are truncated because an error string ends up in logs.
	maxErrorBody = 4 << 10

	// eventStreamBuffer lets the SSE reader stay ahead of a slow consumer for
	// short bursts without blocking the scan loop.
	eventStreamBuffer = 64

	// maxEventSize is the largest single SSE line accepted. Tool results are
	// pre-truncated server-side, so this is a safety valve rather than a limit.
	maxEventSize = 4 << 20

	// authUsername is the only username opencode's basic-auth middleware
	// accepts. The password is generated by `opencode serve` (printed on
	// stdout) or supplied with OPENCODE_PASSWORD/OPENCODE_SERVER_PASSWORD.
	authUsername = "opencode"

	// messagesLimit keeps a single prompt's turn history on one page. The
	// server defaults to a smaller page and returns newest first; the agent
	// wants the whole turn, oldest first.
	messagesLimit = 200
)

// Sentinel errors let callers branch on cause without matching message text.
var (
	// ErrUnauthorized reports a rejected basic-auth credential. The supervisor
	// must not treat it like an unhealthy service and spawn a duplicate.
	ErrUnauthorized = errors.New("opencode: unauthorized")

	// ErrExperimentalUnavailable reports that an endpoint under
	// /api/experimental is missing (404/405), so the caller must fall back to
	// the event feed for terminal state.
	ErrExperimentalUnavailable = errors.New("opencode: experimental endpoint unavailable")
)

// Client talks to a local opencode server. It is stateless beyond its
// endpoints and safe for concurrent use.
type Client struct {
	baseURL string
	// password enables HTTP basic auth; empty disables the Authorization
	// header, which is what older opencode builds without auth expect.
	password string
	// httpClient carries a timeout; it is used for request/response calls.
	httpClient *http.Client
	// streamClient is the same transport with no overall timeout, because the
	// SSE feed and experimental wait are long-lived and are bounded by ctx.
	streamClient *http.Client
}

// Option customizes a Client. It exists so adding authentication did not
// change the two-argument New signature every existing caller uses.
type Option func(*Client)

// WithPassword authenticates requests with HTTP basic auth. opencode's
// username is fixed to "opencode"; only the password varies per process.
func WithPassword(password string) Option {
	return func(c *Client) { c.password = password }
}

// New builds a client for baseURL (for example "http://127.0.0.1:4096").
// A nil httpClient selects the default transport, and a client without a
// timeout gets defaultRequestTimeout for non-streaming requests.
func New(baseURL string, httpClient *http.Client, opts ...Option) *Client {
	if httpClient == nil {
		httpClient = &http.Client{}
	}

	requestClient := *httpClient
	if requestClient.Timeout == 0 {
		requestClient.Timeout = defaultRequestTimeout
	}
	streamClient := *httpClient
	streamClient.Timeout = 0

	c := &Client{
		baseURL:      strings.TrimRight(baseURL, "/"),
		httpClient:   &requestClient,
		streamClient: &streamClient,
	}
	for _, opt := range opts {
		opt(c)
	}
	return c
}

// Health reports whether the server is ready to accept work. opencode v2
// answers GET /api/info with 200 ready, 503 starting/stopping (retry-after),
// 500 failed, and 401 when the password is wrong. Any non-2xx is an error;
// ErrUnauthorized is returned separately so a wrong credential is not retried
// as an unhealthy process.
func (c *Client) Health(ctx context.Context) error {
	return c.doJSON(ctx, http.MethodGet, "/api/info", nil, nil)
}

// ListSessions returns the sessions known to the server, newest first.
func (c *Client) ListSessions(ctx context.Context) ([]Session, error) {
	var sessions []Session
	if err := c.doData(ctx, http.MethodGet, "/api/session", nil, &sessions); err != nil {
		return nil, err
	}
	return sessions, nil
}

// CreateSession opens a session rooted at directory. The server rejects the
// call when directory is not accessible from the process.
func (c *Client) CreateSession(ctx context.Context, directory string) (Session, error) {
	req := createSessionRequest{Location: sessionLocation{Directory: directory}}
	var session Session
	if err := c.doData(ctx, http.MethodPost, "/api/session", req, &session); err != nil {
		return Session{}, err
	}
	return session, nil
}

// Prompt admits text into a session asynchronously and returns the ID of the
// admitted inbox item. Admission only means the prompt was queued; the reply
// text must be read back with Messages once the session goes idle.
func (c *Client) Prompt(ctx context.Context, sessionID, text string) (string, error) {
	path := sessionPath(sessionID) + "/prompt"
	var resp promptResponse
	if err := c.doData(ctx, http.MethodPost, path, promptRequest{Text: text}, &resp); err != nil {
		return "", err
	}
	if resp.ID == "" {
		return "", fmt.Errorf("opencode POST %s: response missing admission id", path)
	}
	return resp.ID, nil
}

// Messages returns the messages of a session in chronological order. The
// final assistant message is the authoritative source of the run's text.
func (c *Client) Messages(ctx context.Context, sessionID string) ([]Message, error) {
	path := fmt.Sprintf("%s/message?order=asc&limit=%d", sessionPath(sessionID), messagesLimit)
	var messages []Message
	if err := c.doData(ctx, http.MethodGet, path, nil, &messages); err != nil {
		return nil, err
	}
	return messages, nil
}

// Wait blocks until the session is idle and returns. It calls the experimental
// endpoint POST /api/experimental/session/{id}/wait and treats 204 as success.
//
// The call is bounded by ctx rather than the default request timeout because a
// real task can run for minutes. A missing endpoint returns
// ErrExperimentalUnavailable so the caller can fall back to
// session.execution.succeeded/failed events.
func (c *Client) Wait(ctx context.Context, sessionID string) error {
	path := "/api/experimental/session/" + url.PathEscape(sessionID) + "/wait"
	err := c.do(ctx, c.streamClient, http.MethodPost, path, nil, nil)
	if err == nil {
		return nil
	}

	var status *statusError
	if errors.As(err, &status) && (status.code == http.StatusNotFound || status.code == http.StatusMethodNotAllowed) {
		return fmt.Errorf("%w: %w", ErrExperimentalUnavailable, err)
	}
	return err
}

// ReplyPermission answers a pending permission request. decision is one of
// "once", "always" or "reject"; message is optional and omitted when empty.
func (c *Client) ReplyPermission(ctx context.Context, sessionID, permissionID, decision, message string) error {
	path := sessionPath(sessionID) + "/permission/" + url.PathEscape(permissionID) + "/reply"
	req := replyPermissionRequest{Decision: decision, Message: message}
	return c.doJSON(ctx, http.MethodPost, path, req, nil)
}

// SubscribeEvents opens the server event feed and returns a buffered channel of
// decoded events. The channel is closed when the stream ends or ctx is
// canceled; callers must keep receiving until then to avoid losing frames.
func (c *Client) SubscribeEvents(ctx context.Context) (<-chan Event, error) {
	const path = "/api/event"

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, c.baseURL+path, nil)
	if err != nil {
		return nil, fmt.Errorf("build opencode %s %s request: %w", http.MethodGet, path, err)
	}
	req.Header.Set("Accept", "text/event-stream")
	c.authorize(req)

	resp, err := c.streamClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("opencode %s %s: %w", http.MethodGet, path, err)
	}
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		defer resp.Body.Close()
		return nil, c.responseError(http.MethodGet, path, resp)
	}

	events := make(chan Event, eventStreamBuffer)
	go func() {
		defer close(events)
		defer resp.Body.Close()
		readEventStream(ctx, resp.Body, events)
	}()
	return events, nil
}

// doJSON performs one request/response call through the bounded client.
func (c *Client) doJSON(ctx context.Context, method, path string, in, out any) error {
	return c.do(ctx, c.httpClient, method, path, in, out)
}

// doData performs one call and unwraps the v2 {"data": ...} envelope into out.
// A response without data is an error rather than an empty value, because the
// agent would otherwise report a phantom success for a malformed reply.
func (c *Client) doData(ctx context.Context, method, path string, in, out any) error {
	var envelope struct {
		Data json.RawMessage `json:"data"`
	}
	if err := c.doJSON(ctx, method, path, in, &envelope); err != nil {
		return err
	}
	if len(envelope.Data) == 0 || bytes.Equal(envelope.Data, []byte("null")) {
		return fmt.Errorf("opencode %s %s: response missing data", method, path)
	}
	if err := json.Unmarshal(envelope.Data, out); err != nil {
		return fmt.Errorf("decode opencode %s %s data: %w", method, path, err)
	}
	return nil
}

// do performs one request/response call with the supplied client, encoding in
// as JSON when non-nil and decoding the body into out when non-nil. Neither the
// request body nor the prompt text is ever included in an error message.
func (c *Client) do(ctx context.Context, httpClient *http.Client, method, path string, in, out any) error {
	var body io.Reader
	if in != nil {
		encoded, err := json.Marshal(in)
		if err != nil {
			return fmt.Errorf("encode opencode %s %s request: %w", method, path, err)
		}
		body = bytes.NewReader(encoded)
	}

	req, err := http.NewRequestWithContext(ctx, method, c.baseURL+path, body)
	if err != nil {
		return fmt.Errorf("build opencode %s %s request: %w", method, path, err)
	}
	if in != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	req.Header.Set("Accept", "application/json")
	c.authorize(req)

	resp, err := httpClient.Do(req)
	if err != nil {
		return fmt.Errorf("opencode %s %s: %w", method, path, err)
	}
	defer resp.Body.Close()

	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return c.responseError(method, path, resp)
	}
	if out == nil {
		// Drain a bounded prefix so the connection can be reused.
		_, _ = io.Copy(io.Discard, io.LimitReader(resp.Body, maxErrorBody))
		return nil
	}
	if err := json.NewDecoder(resp.Body).Decode(out); err != nil {
		return fmt.Errorf("decode opencode %s %s response: %w", method, path, err)
	}
	return nil
}

// authorize attaches the basic-auth credential. opencode accepts only the
// username "opencode"; the password is the per-process secret.
func (c *Client) authorize(req *http.Request) {
	if c.password != "" {
		req.SetBasicAuth(authUsername, c.password)
	}
}

// readEventStream decodes server-sent events from body until the stream ends
// or ctx is canceled. Malformed frames are skipped: the interface has no error
// channel, and a single bad frame must not tear down the feed. Unknown event
// types are preserved for the caller to count.
func readEventStream(ctx context.Context, body io.Reader, events chan<- Event) {
	scanner := bufio.NewScanner(body)
	scanner.Buffer(make([]byte, 0, 64<<10), maxEventSize)

	var data []byte
	dispatch := func() bool {
		if len(data) == 0 {
			return true
		}
		var event Event
		err := json.Unmarshal(data, &event)
		data = data[:0]
		if err != nil {
			return true
		}
		select {
		case events <- event:
			return true
		case <-ctx.Done():
			return false
		}
	}

	for scanner.Scan() {
		line := scanner.Bytes()
		if len(line) == 0 {
			if !dispatch() {
				return
			}
			continue
		}
		if !bytes.HasPrefix(line, []byte("data:")) {
			continue
		}
		value := line[len("data:"):]
		if len(value) > 0 && value[0] == ' ' {
			value = value[1:]
		}
		if len(data) > 0 {
			data = append(data, '\n')
		}
		data = append(data, value...)
	}
	dispatch()
}

// statusError is a non-2xx reply. It is typed so Wait can distinguish a
// missing experimental endpoint from a real server failure.
type statusError struct {
	method string
	path   string
	code   int
	body   string
}

func (e *statusError) Error() string {
	if e.body == "" {
		return fmt.Sprintf("opencode %s %s: status %d", e.method, e.path, e.code)
	}
	return fmt.Sprintf("opencode %s %s: status %d: %s", e.method, e.path, e.code, e.body)
}

// responseError formats a non-2xx reply. The bounded body is included because
// opencode puts the actionable reason there, but request bodies are never
// echoed so prompts and credentials cannot leak through this path.
func (c *Client) responseError(method, path string, resp *http.Response) error {
	detail, _ := io.ReadAll(io.LimitReader(resp.Body, maxErrorBody))
	err := &statusError{
		method: method,
		path:   path,
		code:   resp.StatusCode,
		body:   strings.TrimSpace(string(detail)),
	}
	if resp.StatusCode == http.StatusUnauthorized {
		return fmt.Errorf("%w: %w", ErrUnauthorized, err)
	}
	return err
}

// sessionPath builds the collection path for a session, escaping the ID so a
// hostile or malformed value cannot inject path segments.
func sessionPath(sessionID string) string {
	return "/api/session/" + url.PathEscape(sessionID)
}

// createSessionRequest mirrors the v2 body: the working directory travels
// inside a location object rather than as a top-level field. A top-level
// directory is silently ignored by the server, which was verified against
// v2.0.32.
type createSessionRequest struct {
	Location sessionLocation `json:"location"`
}

type sessionLocation struct {
	Directory string `json:"directory"`
}

type promptRequest struct {
	Text string `json:"text"`
}

// promptResponse is the admitted inbox item. Its ID is the admission identity
// the agent replays for idempotency; v2 does not return a separate "receipt".
type promptResponse struct {
	ID string `json:"id"`
}

type replyPermissionRequest struct {
	Decision string `json:"decision"`
	Message  string `json:"message,omitempty"`
}
